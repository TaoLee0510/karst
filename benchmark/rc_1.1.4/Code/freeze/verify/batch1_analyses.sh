#!/usr/bin/env bash
# Verification of batch 1, step 2: the analysis and summary steps rerun from
# Code/ on copies of the frozen intermediate files (fits linked, never written),
# in RC_HOME/verify/batch1/links. Compared afterwards with compare.R.
#   bash Code/freeze/verify/batch1_analyses.sh      (HPC login node, after the batch 1 copy)
source /etc/profile >/dev/null 2>&1 || true
set -euo pipefail
RC_HOME=$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)
export RC_RESULTS=${RC_HOME}/verify/batch1
source "${RC_HOME}/Code/rc_env.sh"
F=${RC_FROZEN}; L=${RC_RESULTS}/links; mkdir -p "${L}"
mon() { echo "$1 $2 monitor $(rc_monitor "$2")"; }
jid() { awk '/Submitted batch job/ {print $4}' | tail -1; }

## A1 analyses (ABM and Salehi) and A3 (CV against alfak's targets), A4 (one landscape on list E)
R=${L}/round; mkdir -p "${R}/analysis"
ln -sfn "${F}/part1_paper/round_6ae2a24/fits" "${R}/fits"
rsync -a "${F}/part1_paper/round_6ae2a24/tables" "${F}/part1_paper/round_6ae2a24/scores" "${R}/"
rm -f "${R}/tables/xv_alfak_target.Rds"     # regenerated by A3 below
cd "${RC_CODE}/paper"
j=$(BENCH_RESULTS=${R} sbatch --qos=${RC_QOS} --cpus-per-task=4 --mem=64G --time=08:00:00 --exclude=${RC_EXCLUDE} \
      --output=${RC_RESULTS}/logs/paper/%x_%j.out --export=ALL,BENCH_RESULTS=${R} --job-name=v_analyse \
      hpc/collect_analyse.sh analyse_abm analyse_salehi | jid); mon a1_analyse "$j"
j=$(BENCH_RESULTS=${R} KARST_LIB=${RC_CODE}/env/lib/karst_wip SCRIPT_ARGS="scripts/xv_alfak_target.R" \
      bash hpc/submit.sh script 1 48G 03:00:00 | jid); mon a3_xv_alfak_target "$j"
row=$(awk -F'\t' '$1 == "abm" && $2 == "w_0p2_m_5e-05_rep_01" && $3 == "w2_ends" && $4 == "karst" {print NR - 1; exit}' tasks/align_karst/inputs.tsv)
j=$(sbatch --parsable --qos=${RC_QOS} --mem=16G --time=12:00:00 --array=${row} --exclude=${RC_EXCLUDE} --job-name=v_align \
      --output=${RC_RESULTS}/logs/paper/%x_%A_%a.out \
      --export=ALL,BENCH_RESULTS=${R},KARST_LIB=${RC_CODE}/env/lib/karst_wip,ALIGN=karst,BENCH_TASKS=${RC_CODE}/paper/tasks/6ae2a24,ALIGN_TASKS=${RC_CODE}/paper/tasks/align_karst/inputs.tsv \
      hpc/xv_job.sh align_task); mon "a4_align row ${row}" "$j"

## A2 rate-grid comparison and the paper-grid summary
G=${L}/salehi_rate_grid; mkdir -p "${G}"
for m in 01 02 04 08 16 32 64; do mkdir -p "${G}/x${m}"; rsync -a "${F}/part1_paper/salehi_rate_grid/x${m}/analysis" "${F}/part1_paper/salehi_rate_grid/x${m}/tables" "${G}/x${m}/"; done
cp -p "${F}/part1_paper/salehi_rate_grid/dispersion.tsv" "${G}/"
j=$(SCRIPT_ARGS="scripts/beta_grid_compare.R --root=${G} --dispersion=${G}/dispersion.tsv" bash hpc/submit.sh script 1 16G 02:00:00 | jid)
mon a2_compare "$j"
DEPEND=${j} RATE_GRID=${G} bash "${RC_CODE}/hpc/submit_rc.sh" v_paper_grid rc/paper_grid_summary.R "${RC_CODE}/rc/tasks/one.tsv" "${L}/paper_grid"

## B2 summaries from the frozen tables, and the scoring of 20 datasets
O=${L}/own_grid; mkdir -p "${O}"
cp -p "${F}/part2_own/rate_grid/metrics_heldout_grid.csv" "${F}/part2_own/rate_grid/direction_heldout_grid.csv" "${O}/"
for m in 02 04 08 16 32 64; do ln -sfn "${F}/part2_own/rate_grid/x${m}" "${O}/x${m}"; done
MEM=32G bash "${RC_CODE}/hpc/submit_rc.sh" v_own_summary rc/own_grid_summary.R "${RC_CODE}/rc/tasks/one.tsv" "${O}"
OWN_ROUND_FITS=${F}/part2_own/round_6ae2a24/fits MEM=32G bash "${RC_CODE}/hpc/submit_rc.sh" v_own_diag rc/own_grid_diag.R "${RC_CODE}/rc/tasks/one.tsv" "${O}"
S=${L}/own_data_subset; mkdir -p "${S}"
ln -sfn "${RC_DATA}/own_benchmark/datasets" "${S}/datasets"; ln -sfn "${RC_DATA}/own_benchmark/nodes" "${S}/nodes"
awk -F, 'NR == 1 || (NR % 350 == 2)' "${RC_DATA}/own_benchmark/dataset_index_heldout.csv" > "${S}/dataset_index_heldout.csv"
echo "own subset: $(( $(wc -l < "${S}/dataset_index_heldout.csv") - 1 )) datasets"
O2=${L}/own_grid_subset; mkdir -p "${O2}"
for m in 02 04 08 16 32 64; do ln -sfn "${F}/part2_own/rate_grid/x${m}" "${O2}/x${m}"; done
STT_DATA_DIR=${S} OWN_ROUND_FITS=${F}/part2_own/round_6ae2a24/fits CPUS=4 OR_CORES=4 MEM=32G \
  bash "${RC_CODE}/hpc/submit_rc.sh" v_own_score rc/own_score.R "${RC_CODE}/rc/tasks/one.tsv" "${O2}"
STT_DATA_DIR=${S} OWN_ROUND_FITS=${F}/part2_own/round_6ae2a24/fits CPUS=4 OR_CORES=4 MEM=32G \
  bash "${RC_CODE}/hpc/submit_rc.sh" v_own_direction rc/own_direction.R "${RC_CODE}/rc/tasks/one.tsv" "${O2}"

## D Kester scores and summary from the frozen fits
K=${L}/kester; mkdir -p "${K}"
cp -p "${F}/part3_kester/tasks.tsv" "${F}/part3_kester/fold_manifest.tsv" "${K}/"
rsync -a "${F}/part3_kester/inputs" "${K}/"; ln -sfn "${F}/part3_kester/fits" "${K}/fits"
j=$(CPUS=16 OR_CORES=16 MEM=64G bash "${RC_CODE}/hpc/submit_rc.sh" v_kester_score kester/kester_score.R "${RC_CODE}/rc/tasks/one.tsv" "${K}" | awk '{print $2}')
echo "kester score ${j}"
DEPEND=${j} bash "${RC_CODE}/hpc/submit_rc.sh" v_kester_summary kester/kester_summary.R "${RC_CODE}/rc/tasks/one.tsv" "${K}"
